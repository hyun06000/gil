//! Retirement of generated Host hooks. No registry or Project writes; no automatic enrollment.
use super::*;
use sha2::{Digest, Sha256};
use std::fs::{self, OpenOptions};
use std::io::Write;

fn fingerprint(s: &crate::ReadOnlySession) -> Result<String, String> {
    Ok(format!(
        "{:x}",
        Sha256::digest(fs::read(s.state_path()).map_err(|e| e.to_string())?)
    ))
}
fn waiting(s: &crate::ReadOnlySession) -> bool {
    let project = s.project();
    let cycle = project.current_cycle();
    let Some(node) = cycle.step_now_open().and_then(|id| cycle.steps().node(id)) else {
        return false;
    };
    if node.kind == crate::NodeKind::Question {
        return true;
    }
    if node.kind == crate::NodeKind::Synthesis {
        if let Some(plan) = project.approved_plan() {
            return plan.current(project).is_some_and(|p| p.receipt.is_none());
        }
        return !cfg!(feature = "approved-plan");
    }
    false
}
/// Pure handoff validation: no consent, completion, Project mutation or persistent token.
pub(crate) fn await_user(root: &str, question: &str) -> Result<Value, String> {
    if question.trim().is_empty() || question.len() > 4000 {
        return Err("사용자에게 물을 구체적인 질문이 필요하다 (1..4000 bytes)".into());
    }
    let root = project_root(&crate::mcp::resolve_guard_root(root)?)?;
    let s = session(&root)?;
    if !waiting(&s) {
        return Err("gil_await_user는 열린 Question 또는 제안이 등록된 승인 대기 Synthesis의 선택적 읽기 확인이다. 이 도구 없이도 턴을 끝내거나 Monitor 승인을 기다릴 수 있다. 현재 위치는 gil_context로 확인하며 대기 확인을 위해 Step/Cycle을 만들지 않는다.".into());
    }
    Ok(
        json!({"project_root":root,"state_digest":fingerprint(&s)?,"question":question,"status":"awaiting_user"}),
    )
}

fn home() -> Result<PathBuf, String> {
    let home = PathBuf::from(std::env::var_os("HOME").ok_or("HOME unavailable")?);
    if !home.is_absolute() {
        return Err("HOME must be absolute".into());
    }
    Ok(home)
}
fn regular(path: &Path) -> Result<(), String> {
    match fs::symlink_metadata(path) {
        Ok(m) if m.is_file() && !m.file_type().is_symlink() => Ok(()),
        Err(e) if e.kind() == io::ErrorKind::NotFound => Ok(()),
        _ => Err("Host settings must be regular files; preserved".into()),
    }
}
fn hosts(host: &str) -> Result<&'static [&'static str], String> {
    match host {
        "both" => Ok(&["codex", "claude"]),
        "codex" => Ok(&["codex"]),
        "claude" => Ok(&["claude"]),
        _ => Err("host must be codex, claude, or both".into()),
    }
}
fn path(home: &Path, host: &str) -> PathBuf {
    home.join(if host == "codex" {
        ".codex/hooks.json"
    } else {
        ".claude/settings.json"
    })
}

// Parse only the canonical quoting generated by invocation(), never shell syntax or a suffix.
fn generated_hook(command: &str) -> bool {
    let mut rest = command;
    let mut words = Vec::new();
    while !rest.is_empty() {
        let Some(mut tail) = rest.strip_prefix('\'') else {
            return false;
        };
        let mut word = String::new();
        loop {
            let Some(end) = tail.find('\'') else {
                return false;
            };
            word.push_str(&tail[..end]);
            tail = &tail[end + 1..];
            if let Some(next) = tail.strip_prefix("\\''") {
                word.push('\'');
                tail = next;
            } else {
                break;
            }
        }
        words.push(word);
        if tail.is_empty() {
            break;
        }
        let Some(next) = tail.strip_prefix(' ') else {
            return false;
        };
        rest = next;
        if rest.is_empty() {
            return false;
        }
    }
    let Some(exe) = words.first() else {
        return false;
    };
    let exe = Path::new(exe);
    if !exe.is_absolute() {
        return false;
    }
    let offset = match exe.file_stem().and_then(|s| s.to_str()) {
        Some("gil") if words.get(1).is_some_and(|s| s == "write-guard") => 2,
        Some("gil-write-guard") => 1,
        _ => return false,
    };
    let args: Vec<_> = words[offset..].iter().map(String::as_str).collect();
    let supported = match args.as_slice() {
        ["hook", "--auto"] => true,
        ["hook", "--auto", "--host", "codex" | "claude"] => true,
        ["hook", "--root", root] => Path::new(root).is_absolute(),
        _ => false,
    };
    supported && invocation(exe, &args).is_ok_and(|expected| expected == command)
}
fn owned(hook: &Value) -> bool {
    hook["type"] == "command" && hook["command"].as_str().is_some_and(generated_hook)
}
fn suspicious(hook: &Value) -> bool {
    ["command", "commandWindows"].iter().any(|key| {
        hook[*key]
            .as_str()
            .is_some_and(|s| s.contains("write-guard") && s.contains("hook"))
    })
}
fn clean(settings: &mut Value) -> Result<usize, String> {
    inventory(settings)?;
    let object = settings
        .as_object_mut()
        .ok_or("Host settings must be an object; preserved")?;
    let Some(value) = object.get_mut("hooks") else {
        return Ok(0);
    };
    let hooks = value
        .as_object_mut()
        .ok_or("invalid existing hooks; preserved")?;
    let mut removed = 0;
    let mut empty_after_removal = Vec::new();
    for (event, entries) in hooks.iter_mut() {
        let removed_before = removed;
        let rows = entries
            .as_array_mut()
            .ok_or("invalid hook event; preserved")?;
        rows.retain_mut(|row| {
            let Some(commands) = row.get_mut("hooks").and_then(Value::as_array_mut) else {
                return true;
            };
            let before = commands.len();
            commands.retain(|h| !owned(h));
            removed += before - commands.len();
            before == commands.len() || !commands.is_empty()
        });
        if removed > removed_before && rows.is_empty() {
            empty_after_removal.push(event.clone());
        }
    }
    if removed > 0 {
        for event in empty_after_removal {
            hooks.remove(&event);
        }
        if hooks.is_empty() {
            object.remove("hooks");
        }
    }
    Ok(removed)
}
fn inventory(settings: &Value) -> Result<(usize, usize), String> {
    let object = settings.as_object().ok_or("invalid settings")?;
    let Some(value) = object.get("hooks") else {
        return Ok((0, 0));
    };
    let mut generated = 0;
    let mut custom = 0;
    for rows in value.as_object().ok_or("invalid hooks")?.values() {
        for row in rows.as_array().ok_or("invalid event")? {
            for hook in row
                .get("hooks")
                .and_then(Value::as_array)
                .ok_or("invalid hook row")?
            {
                if !hook.is_object() {
                    return Err("invalid hook entry".into());
                }
                if owned(hook) {
                    generated += 1;
                } else if suspicious(hook) {
                    custom += 1;
                }
            }
        }
    }
    Ok((generated, custom))
}
fn status(home: &Path) -> Value {
    let mut result = serde_json::Map::new();
    for host in ["codex", "claude"] {
        let path = path(home, host);
        let state = match regular(&path)
            .and_then(|()| match fs::read(&path) {
                Ok(bytes) => {
                    serde_json::from_slice::<Value>(&bytes).map_err(|_| "invalid settings".into())
                }
                Err(e) if e.kind() == io::ErrorKind::NotFound => Ok(json!({})),
                Err(e) => Err(e.to_string()),
            })
            .and_then(|v| inventory(&v))
        {
            Ok((generated, custom)) => json!({"status":if generated > 0 {"removal_required"}
                else if custom > 0 {"custom_review_required"} else {"not_installed"},
                "generated_commands":generated,"custom_commands_for_review":custom}),
            Err(_) => json!({"status":"unreadable_or_invalid_settings"}),
        };
        result.insert(host.into(), state);
    }
    json!({"policy":"no_host_hooks","installed_hooks":result,"registry_used":false,
        "scope":"Known Host JSON settings only; loaded sessions and custom scripts require review"})
}
fn uninstall(home: &Path, host: &str) -> Result<Value, String> {
    // Preflight every selected Host before changing any setting. Missing settings stay absent.
    let mut plans = Vec::new();
    let mut updated = Vec::new();
    for host in hosts(host)? {
        let path = path(home, host);
        regular(&path)?;
        if !path.exists() {
            updated.push(json!({"host":host,"changed":false}));
            continue;
        }
        let old = fs::read(&path).map_err(|e| e.to_string())?;
        let mut settings: Value =
            serde_json::from_slice(&old).map_err(|_| "invalid existing Host JSON; preserved")?;
        let removed = clean(&mut settings)?;
        if removed == 0 {
            updated.push(json!({"host":host,"changed":false}));
            continue;
        }
        let mut next = serde_json::to_vec_pretty(&settings).map_err(|e| e.to_string())?;
        next.push(b'\n');
        plans.push((*host, path, old, next, removed));
    }
    if !plans.is_empty() {
        let dir = home.join(".gil-host-guard");
        if !dir.exists() {
            let mut builder = fs::DirBuilder::new();
            #[cfg(unix)]
            {
                use std::os::unix::fs::DirBuilderExt;
                builder.mode(0o700);
            }
            builder.create(&dir).map_err(|e| e.to_string())?;
        }
        let metadata = fs::symlink_metadata(&dir).map_err(|e| e.to_string())?;
        if !metadata.is_dir() || metadata.file_type().is_symlink() {
            return Err("unsafe backup directory; preserved".into());
        }
        #[cfg(unix)]
        {
            use std::os::unix::fs::MetadataExt;
            if metadata.mode() & 0o077 != 0 {
                return Err("backup directory must be private (0700); preserved".into());
            }
        }
        let lock = dir.join("cleanup.lock");
        regular(&lock)?;
        let mut opts = OpenOptions::new();
        opts.write(true).read(true).create(true).truncate(false);
        #[cfg(unix)]
        {
            use std::os::unix::fs::OpenOptionsExt;
            opts.mode(0o600);
        }
        let lock = opts.open(lock).map_err(|e| e.to_string())?;
        lock.try_lock()
            .map_err(|_| "another hook cleanup is running; preserved")?;
        for (_, path, old, _, _) in &plans {
            regular(path)?;
            if fs::read(path).map_err(|e| e.to_string())? != *old {
                return Err("settings changed concurrently; preserved".into());
            }
        }
        for (host, path, old, next, removed) in plans {
            let stamp = std::time::SystemTime::now()
                .duration_since(std::time::UNIX_EPOCH)
                .map_err(|e| e.to_string())?
                .as_nanos();
            let backup = dir.join(format!("{host}-settings-{stamp}.json"));
            let mut opts = OpenOptions::new();
            opts.write(true).create_new(true);
            #[cfg(unix)]
            {
                use std::os::unix::fs::OpenOptionsExt;
                opts.mode(0o600);
            }
            opts.open(&backup)
                .and_then(|mut f| {
                    f.write_all(&old)?;
                    f.sync_all()
                })
                .map_err(|e| e.to_string())?;
            let tmp = path
                .parent()
                .ok_or("missing Host directory")?
                .join(format!(".gil-unhook-{stamp}.tmp"));
            opts.open(&tmp)
                .and_then(|mut f| {
                    f.write_all(&next)?;
                    f.sync_all()
                })
                .map_err(|e| e.to_string())?;
            regular(&path)?;
            if fs::read(&path).map_err(|e| e.to_string())? != old {
                let _ = fs::remove_file(&tmp);
                return Err("settings changed concurrently; original preserved".into());
            }
            fs::rename(&tmp, &path).map_err(|e| e.to_string())?;
            updated.push(
                json!({"host":host,"changed":true,"removed_commands":removed,"backup":backup}),
            );
        }
    }
    Ok(
        json!({"updated":updated,"policy":"no_host_hooks","installed_hooks":status(home)["installed_hooks"],
        "activation":"Restart Hosts/new sessions to discard previously loaded hooks. No trust, permissions, registry or Project changes."}),
    )
}
pub(super) fn dispatch(args: &[String]) -> Result<u8, String> {
    match args.first().map(String::as_str) {
        Some("config") => { println!("{}", json!({"hooks":{}})); Ok(0) }
        Some("install") => Err("Global GIL hooks are retired. Use write-guard uninstall --auto --host codex|claude|both. Do not install project or plugin hooks.".into()),
        Some("uninstall") if args.len() == 4 && args[2] == "--host" => {
            println!("{}", uninstall(&home()?, &args[3])?); Ok(0)
        }
        Some("status") if args.len() == 2 => { println!("{}", status(&home()?)); Ok(0) }
        Some("run") => Err("Automatic GIL sandbox wrapping is retired. Use the Host's ordinary execution and permission flow; GIL guidance applies only to the selected project.".into()),
        _ => Err("usage: write-guard uninstall --auto --host codex|claude|both | status --auto".into()),
    }
}
